// Writes src/presets/tech-data.ts from case-police's dictionaries.
// Run `node scripts/tech.ts` after changing the pinned case-police version.
//
// How the pinned case-police 2.2.1 reads these files (`replaceCore` in dist/shared):
// - Each key is the lookup: the regex is every key, longest first, matched whole-word and in any
//   case. The value is the canonical spelling it writes back.
// - A match with no capital or no lowercase letter is left alone, so `github` and `GITHUB` pass
//   and `Github` becomes `GitHub`. Every term here therefore skips `lower` and `upper`.
// - 13 keys differ from their value beyond case (`nextjs` -> `Next.js`, `vscode` -> `VS Code`),
//   and only by spaces, dots or hyphens, which glosslint's word splitting already covers.
// - Several keys share one value once separators are removed (`ant design` -> `Ant Design`,
//   `antdesign` -> `AntDesign`). A corpus holds one term per key, so the first value in key order
//   becomes the term, and any other spelling goes to `allow`, where case-police accepts it too.
// - A spaced key of a one-word term (`web assembly` -> `WebAssembly`) goes to the term's `avoid`,
//   since glosslint reads an exact one-word name split at spaces as a phrase unless it is listed.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const pkgDir = new URL("../node_modules/case-police/", import.meta.url);
const dictDir = new URL("dict/", pkgDir);
const { version } = JSON.parse(readFileSync(new URL("package.json", pkgDir), "utf8")) as {
  version: string;
};
const outFile = new URL("../src/presets/tech-data.ts", import.meta.url);

const key = (text: string) => text.toLowerCase().replace(/[\s._-]+/g, "");

const counts: Record<string, number> = {};
const entries: [lookup: string, canonical: string][] = [];
const files = readdirSync(dictDir).filter((name) => name.endsWith(".json"));
for (const file of files.sort()) {
  const dict = JSON.parse(readFileSync(new URL(file, dictDir), "utf8")) as Record<string, string>;
  counts[file.replace(/\.json$/, "")] = Object.keys(dict).length;
  entries.push(...Object.entries(dict));
}
entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const terms = new Map<string, string>();
const allow = new Set<string>();
for (const [, canonical] of entries) {
  const existing = terms.get(key(canonical));
  if (existing === undefined) terms.set(key(canonical), canonical);
  else if (existing !== canonical) allow.add(canonical);
}

const avoid = new Map<string, string[]>();
for (const [lookup] of entries) {
  const term = terms.get(key(lookup));
  if (term === undefined || !/\s/.test(lookup) || /\s/.test(term)) continue;
  avoid.set(key(lookup), [...(avoid.get(key(lookup)) ?? []), lookup]);
}

const byKey = (a: string, b: string) => {
  const [x, y] = [key(a), key(b)];
  return x < y ? -1 : x > y ? 1 : a < b ? -1 : 1;
};
const total = Object.values(counts).reduce((sum, n) => sum + n, 0);
const lines = [
  `// Generated by scripts/tech.ts from case-police ${version} (MIT, see NOTICE). Do not edit.`,
  "// Regenerate with `node scripts/tech.ts`.",
  'import type { Term } from "../types.ts";',
  "",
  `/** How many entries each case-police dictionary has: ${total} in all. */`,
  "export const counts = {",
  ...Object.entries(counts).map(([name, n]) => `  ${name}: ${n},`),
  "};",
  "",
  "/** Spellings case-police also accepts that share a term's key, such as `AntDesign`. */",
  "export const allow: string[] = [",
  ...[...allow].sort(byKey).map((word) => `  ${JSON.stringify(word)},`),
  "];",
  "",
  "/** One `exact` term per canonical spelling, passing all-lowercase and all-capitals words. */",
  "export const terms: Term[] = [",
  ...[...terms.values()].sort(byKey).map((term) => {
    const spaced = avoid.get(key(term));
    const extra = spaced ? `, avoid: ${JSON.stringify(spaced).replaceAll(",", ", ")}` : "";
    return `  { term: ${JSON.stringify(term)}, case: "exact", skip: ["lower", "upper"]${extra} },`;
  }),
  "];",
  "",
];
writeFileSync(outFile, lines.join("\n"));
console.log(`${total} entries, ${terms.size} terms, ${allow.size} allowed spellings`);
